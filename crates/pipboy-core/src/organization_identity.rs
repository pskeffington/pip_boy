//! ORG-3 proof-of-possession evidence for a prospective RB session.
//!
//! Verifies Ed25519-signed device/operator credentials and challenge signatures
//! against a caller-supplied trusted org root. It cannot attest that this root,
//! the time, channel binding, or revocation list is fresh or administratively
//! authorized. A successful result is NEVER sufficient to open an API or send
//! data. No key generation, I/O, authentication session, or live routing here.
use crate::organization::{Dataset, GrantAction, OrgGraph};
use crate::organization_policy::{preflight, Preflight, ProposedExchange};
use ring::signature::{UnparsedPublicKey, ED25519};
use serde::{Deserialize, Serialize};

const CREDENTIAL_DOMAIN: &[u8] = b"rust-boy.org.credential.v1\0";
const PROOF_DOMAIN: &[u8] = b"rust-boy.org.proof.v1\0";
const KEY_BYTES: usize = 32;
const SIGNATURE_BYTES: usize = 64;

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum PrincipalKind {
    Operator,
    Device,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SignedCredential {
    pub schema_version: u32,
    pub organization_id: String,
    pub vault_id: String,
    pub principal_kind: PrincipalKind,
    pub principal_id: String,
    pub serial: u64,
    pub key_epoch: u64,
    pub not_before: u64,
    pub expires_at: u64,
    pub public_key: Vec<u8>,
    pub issuer_signature: Vec<u8>,
}

/// The signature binds the public-key holder to a fresh, channel-bound
/// challenge. The caller MUST enforce nonce uniqueness and TLS/SSH channel
/// binding; this pure module has no replay journal or transport.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SessionProof {
    pub signature: Vec<u8>,
}

pub struct VerificationContext<'a> {
    /// Trusted by configuration OUTSIDE this module; never accept from peer.
    pub organization_public_key: &'a [u8],
    /// Must be supplied by an authenticated clock/time authority.
    pub verified_now: u64,
    /// Challenge generated by verifier using a CSPRNG and tracked once.
    pub nonce: &'a [u8; KEY_BYTES],
    /// Authenticated session exporter/transcript digest from live transport.
    pub channel_binding: &'a [u8; KEY_BYTES],
    /// A verified and freshness-checked revocation snapshot is required.
    pub revoked_serials: &'a [u64],
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct IdentityEvidence {
    pub organization_id: String,
    pub vault_id: String,
    pub operator_id: String,
    pub device_id: String,
    pub operator_serial: u64,
    pub device_serial: u64,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum EvidenceError {
    InvalidContext,
    StructuralPreflight,
    InvalidCredential,
    ScopeMismatch,
    ExpiredOrPremature,
    Revoked,
    InvalidIssuerSignature,
    InvalidSessionProof,
}

fn valid_id(value: &str) -> bool {
    (2..=64).contains(&value.len())
        && value.as_bytes().first().is_some_and(u8::is_ascii_lowercase)
        && !value.ends_with('-')
        && !value.contains("--")
        && value
            .bytes()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == b'-')
}

fn append_str(out: &mut Vec<u8>, text: &str) {
    out.extend_from_slice(&(text.len() as u16).to_be_bytes());
    out.extend_from_slice(text.as_bytes());
}

fn kind_byte(kind: PrincipalKind) -> u8 {
    match kind {
        PrincipalKind::Operator => 1,
        PrincipalKind::Device => 2,
    }
}

fn action_byte(action: GrantAction) -> u8 {
    match action {
        GrantAction::View => 1,
        GrantAction::Assign => 2,
        GrantAction::Update => 3,
        GrantAction::Sync => 4,
    }
}

fn dataset_byte(dataset: Dataset) -> u8 {
    match dataset {
        Dataset::Mission => 1,
        Dataset::Progress => 2,
        Dataset::Message => 3,
        Dataset::Site => 4,
    }
}

/// Fixed-length and length-prefixed binary encoding, independent of JSON
/// field order. Domain-separated from session proofs and future wire formats.
pub(crate) fn credential_transcript(claim: &SignedCredential) -> Vec<u8> {
    let mut out = CREDENTIAL_DOMAIN.to_vec();
    out.extend_from_slice(&claim.schema_version.to_be_bytes());
    append_str(&mut out, &claim.organization_id);
    append_str(&mut out, &claim.vault_id);
    out.push(kind_byte(claim.principal_kind));
    append_str(&mut out, &claim.principal_id);
    out.extend_from_slice(&claim.serial.to_be_bytes());
    out.extend_from_slice(&claim.key_epoch.to_be_bytes());
    out.extend_from_slice(&claim.not_before.to_be_bytes());
    out.extend_from_slice(&claim.expires_at.to_be_bytes());
    out.extend_from_slice(&claim.public_key);
    out
}

pub(crate) fn proof_transcript(
    query: &ProposedExchange<'_>,
    credential: &SignedCredential,
    nonce: &[u8; KEY_BYTES],
    binding: &[u8; KEY_BYTES],
) -> Vec<u8> {
    let mut out = PROOF_DOMAIN.to_vec();
    append_str(&mut out, query.organization_id);
    append_str(&mut out, query.vault_id);
    append_str(&mut out, query.operator_id);
    append_str(&mut out, query.device_id);
    out.push(action_byte(query.action));
    out.push(dataset_byte(query.dataset));
    out.push(kind_byte(credential.principal_kind));
    out.extend_from_slice(&credential.serial.to_be_bytes());
    out.extend_from_slice(&credential.key_epoch.to_be_bytes());
    out.extend_from_slice(nonce);
    out.extend_from_slice(binding);
    out
}

fn verify_one(
    credential: &SignedCredential,
    proof: &SessionProof,
    expected_kind: PrincipalKind,
    expected_id: &str,
    query: &ProposedExchange<'_>,
    context: &VerificationContext<'_>,
) -> Result<(), EvidenceError> {
    if credential.schema_version != 1
        || !valid_id(&credential.organization_id)
        || !valid_id(&credential.vault_id)
        || !valid_id(&credential.principal_id)
        || credential.serial == 0
        || credential.key_epoch == 0
        || credential.public_key.len() != KEY_BYTES
        || credential.issuer_signature.len() != SIGNATURE_BYTES
        || proof.signature.len() != SIGNATURE_BYTES
        || credential.not_before >= credential.expires_at
    {
        return Err(EvidenceError::InvalidCredential);
    }
    if credential.organization_id != query.organization_id
        || credential.vault_id != query.vault_id
        || credential.principal_id != expected_id
        || credential.principal_kind != expected_kind
    {
        return Err(EvidenceError::ScopeMismatch);
    }
    if !(credential.not_before <= context.verified_now
        && context.verified_now < credential.expires_at)
    {
        return Err(EvidenceError::ExpiredOrPremature);
    }
    if context.revoked_serials.contains(&credential.serial) {
        return Err(EvidenceError::Revoked);
    }
    UnparsedPublicKey::new(&ED25519, context.organization_public_key)
        .verify(
            &credential_transcript(credential),
            &credential.issuer_signature,
        )
        .map_err(|_| EvidenceError::InvalidIssuerSignature)?;
    UnparsedPublicKey::new(&ED25519, &credential.public_key)
        .verify(
            &proof_transcript(query, credential, context.nonce, context.channel_binding),
            &proof.signature,
        )
        .map_err(|_| EvidenceError::InvalidSessionProof)
}

/// Produces evidence for a future policy decision point, not an authorization.
/// Local actor, root, nonce, clock and channel-binding integrity all depend on
/// an external trusted session service which is NOT presently implemented.
pub fn verify_pair(
    graph: &OrgGraph,
    query: &ProposedExchange<'_>,
    context: &VerificationContext<'_>,
    operator: (&SignedCredential, &SessionProof),
    device: (&SignedCredential, &SessionProof),
) -> Result<IdentityEvidence, EvidenceError> {
    if context.organization_public_key.len() != KEY_BYTES
        || context.nonce.iter().all(|n| *n == 0)
        || context.channel_binding.iter().all(|n| *n == 0)
    {
        return Err(EvidenceError::InvalidContext);
    }
    // Ignore caller's unverified timestamp. Only the externally validated
    // trusted time may be used for structural appointments and draft grants.
    let checked = ProposedExchange {
        time_unverified: context.verified_now,
        ..*query
    };
    if preflight(graph, &checked) != Preflight::CandidateForVerification {
        return Err(EvidenceError::StructuralPreflight);
    }
    verify_one(
        operator.0,
        operator.1,
        PrincipalKind::Operator,
        query.operator_id,
        &checked,
        context,
    )?;
    verify_one(
        device.0,
        device.1,
        PrincipalKind::Device,
        query.device_id,
        &checked,
        context,
    )?;
    if operator.0.serial == device.0.serial {
        return Err(EvidenceError::InvalidCredential);
    }
    Ok(IdentityEvidence {
        organization_id: query.organization_id.into(),
        vault_id: query.vault_id.into(),
        operator_id: query.operator_id.into(),
        device_id: query.device_id.into(),
        operator_serial: operator.0.serial,
        device_serial: device.0.serial,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::organization::{
        Appointment, DeviceLifecycle, DeviceRecord, Grant, GrantSubject, Operator, Organization,
        Unit, UnitKind, VaultSite,
    };
    use ring::signature::{Ed25519KeyPair, KeyPair};

    const NONCE: [u8; KEY_BYTES] = [19; KEY_BYTES];
    const BINDING: [u8; KEY_BYTES] = [23; KEY_BYTES];

    fn key(seed: u8) -> Ed25519KeyPair {
        // Deterministic TEST-ONLY secrets, never installed on actual devices.
        Ed25519KeyPair::from_seed_unchecked(&[seed; KEY_BYTES]).unwrap()
    }

    fn query() -> ProposedExchange<'static> {
        ProposedExchange {
            organization_id: "sample-org",
            vault_id: "sample-vault",
            operator_id: "sample-operator",
            device_id: "sample-device",
            action: GrantAction::Sync,
            dataset: Dataset::Progress,
            time_unverified: 20,
        }
    }

    fn credential(
        root: &Ed25519KeyPair,
        holder: &Ed25519KeyPair,
        kind: PrincipalKind,
        subject: &str,
        serial: u64,
    ) -> SignedCredential {
        let mut claim = SignedCredential {
            schema_version: 1,
            organization_id: "sample-org".into(),
            vault_id: "sample-vault".into(),
            principal_kind: kind,
            principal_id: subject.into(),
            serial,
            key_epoch: 1,
            not_before: 10,
            expires_at: 100,
            public_key: holder.public_key().as_ref().to_vec(),
            issuer_signature: Vec::new(),
        };
        claim.issuer_signature = root.sign(&credential_transcript(&claim)).as_ref().to_vec();
        claim
    }

    fn proof(
        holder: &Ed25519KeyPair,
        claim: &SignedCredential,
        q: &ProposedExchange<'_>,
    ) -> SessionProof {
        SessionProof {
            signature: holder
                .sign(&proof_transcript(q, claim, &NONCE, &BINDING))
                .as_ref()
                .to_vec(),
        }
    }

    fn graph() -> OrgGraph {
        OrgGraph {
            schema_version: 1,
            organizations: vec![Organization {
                id: "sample-org".into(),
                name: "Sample Org".into(),
            }],
            vaults: vec![VaultSite {
                id: "sample-vault".into(),
                organization_id: "sample-org".into(),
                name: "Sample Vault".into(),
            }],
            units: vec![Unit {
                id: "sample-team".into(),
                vault_id: "sample-vault".into(),
                parent_unit_id: None,
                kind: UnitKind::Division,
                name: "Field Team".into(),
            }],
            operators: vec![
                Operator {
                    id: "sample-operator".into(),
                    organization_id: "sample-org".into(),
                    display_name: "Sample Operator".into(),
                    active: true,
                },
                Operator {
                    id: "sample-issuer".into(),
                    organization_id: "sample-org".into(),
                    display_name: "Sample Issuer".into(),
                    active: true,
                },
            ],
            appointments: vec![Appointment {
                id: "sample-shift".into(),
                operator_id: "sample-operator".into(),
                unit_id: "sample-team".into(),
                position_id: "recon".into(),
                approved_by_operator_id: "sample-issuer".into(),
                not_before: 10,
                expires_at: 100,
                revoked: false,
            }],
            devices: vec![DeviceRecord {
                id: "sample-device".into(),
                organization_id: "sample-org".into(),
                vault_id: "sample-vault".into(),
                assigned_operator_id: Some("sample-operator".into()),
                lifecycle: DeviceLifecycle::RecordedActive,
            }],
            grants: vec![
                Grant {
                    id: "sample-user-grant".into(),
                    organization_id: "sample-org".into(),
                    issuer_operator_id: "sample-issuer".into(),
                    subject: GrantSubject::Operator("sample-operator".into()),
                    vault_id: "sample-vault".into(),
                    action: GrantAction::Sync,
                    dataset: Dataset::Progress,
                    not_before: 10,
                    expires_at: 100,
                    revoked: false,
                },
                Grant {
                    id: "sample-device-grant".into(),
                    organization_id: "sample-org".into(),
                    issuer_operator_id: "sample-issuer".into(),
                    subject: GrantSubject::Device("sample-device".into()),
                    vault_id: "sample-vault".into(),
                    action: GrantAction::Sync,
                    dataset: Dataset::Progress,
                    not_before: 10,
                    expires_at: 100,
                    revoked: false,
                },
            ],
        }
    }

    struct Fixture {
        graph: OrgGraph,
        root: Ed25519KeyPair,
        operator: SignedCredential,
        device: SignedCredential,
        operator_proof: SessionProof,
        device_proof: SessionProof,
    }

    fn fixture() -> Fixture {
        let root = key(11);
        let operator_key = key(12);
        let device_key = key(13);
        let q = query();
        let operator = credential(
            &root,
            &operator_key,
            PrincipalKind::Operator,
            q.operator_id,
            1,
        );
        let device = credential(&root, &device_key, PrincipalKind::Device, q.device_id, 2);
        Fixture {
            graph: graph(),
            operator_proof: proof(&operator_key, &operator, &q),
            device_proof: proof(&device_key, &device, &q),
            root,
            operator,
            device,
        }
    }

    fn check(
        f: &Fixture,
        q: &ProposedExchange<'_>,
        nonce: &[u8; KEY_BYTES],
        binding: &[u8; KEY_BYTES],
        now: u64,
        revoked: &[u64],
    ) -> Result<IdentityEvidence, EvidenceError> {
        let context = VerificationContext {
            organization_public_key: f.root.public_key().as_ref(),
            verified_now: now,
            nonce,
            channel_binding: binding,
            revoked_serials: revoked,
        };
        verify_pair(
            &f.graph,
            q,
            &context,
            (&f.operator, &f.operator_proof),
            (&f.device, &f.device_proof),
        )
    }

    #[test]
    fn signed_pair_has_matching_scopes_and_distinct_device_keys() {
        let f = fixture();
        let evidence = check(&f, &query(), &NONCE, &BINDING, 20, &[]).unwrap();
        assert_eq!(evidence.organization_id, "sample-org");
        assert_eq!(evidence.operator_serial, 1);
        assert_eq!(evidence.device_serial, 2);
        assert_ne!(f.operator.public_key, f.device.public_key);
    }

    #[test]
    fn untrusted_root_and_tampered_credentials_are_rejected() {
        let f = fixture();
        let wrong_root = key(30);
        let context = VerificationContext {
            organization_public_key: wrong_root.public_key().as_ref(),
            verified_now: 20,
            nonce: &NONCE,
            channel_binding: &BINDING,
            revoked_serials: &[],
        };
        assert_eq!(
            verify_pair(
                &f.graph,
                &query(),
                &context,
                (&f.operator, &f.operator_proof),
                (&f.device, &f.device_proof),
            ),
            Err(EvidenceError::InvalidIssuerSignature)
        );
        let mut f = fixture();
        f.device.public_key[0] ^= 0x01;
        assert_eq!(
            check(&f, &query(), &NONCE, &BINDING, 20, &[]),
            Err(EvidenceError::InvalidIssuerSignature)
        );
        let mut f = fixture();
        f.device.issuer_signature[0] ^= 0x01;
        assert_eq!(
            check(&f, &query(), &NONCE, &BINDING, 20, &[]),
            Err(EvidenceError::InvalidIssuerSignature)
        );
    }

    #[test]
    fn session_nonce_channel_action_and_subject_are_bound() {
        let f = fixture();
        assert_eq!(
            check(&f, &query(), &[99; KEY_BYTES], &BINDING, 20, &[]),
            Err(EvidenceError::InvalidSessionProof)
        );
        assert_eq!(
            check(&f, &query(), &NONCE, &[88; KEY_BYTES], 20, &[]),
            Err(EvidenceError::InvalidSessionProof)
        );
        let mut f = fixture();
        f.device_proof.signature[0] ^= 1;
        assert_eq!(
            check(&f, &query(), &NONCE, &BINDING, 20, &[]),
            Err(EvidenceError::InvalidSessionProof)
        );
        let mut q = query();
        q.action = GrantAction::View;
        assert_eq!(
            check(&fixture(), &q, &NONCE, &BINDING, 20, &[]),
            Err(EvidenceError::StructuralPreflight)
        );
        let mut f = fixture();
        f.device.principal_id = "another-device".into();
        assert_eq!(
            check(&f, &query(), &NONCE, &BINDING, 20, &[]),
            Err(EvidenceError::ScopeMismatch)
        );
    }

    #[test]
    fn revocation_lease_expiry_and_absent_grants_fail_closed() {
        let f = fixture();
        assert_eq!(
            check(&f, &query(), &NONCE, &BINDING, 20, &[2]),
            Err(EvidenceError::Revoked)
        );
        assert_eq!(
            check(&f, &query(), &NONCE, &BINDING, 100, &[]),
            Err(EvidenceError::StructuralPreflight)
        );
        let mut f = fixture();
        f.graph.grants.pop();
        assert_eq!(
            check(&f, &query(), &NONCE, &BINDING, 20, &[]),
            Err(EvidenceError::StructuralPreflight)
        );
        let mut f = fixture();
        f.device.expires_at = 21;
        assert_eq!(
            check(&f, &query(), &NONCE, &BINDING, 21, &[]),
            Err(EvidenceError::ExpiredOrPremature)
        );
    }

    #[test]
    fn wrong_organization_device_and_session_context_fail_closed() {
        let f = fixture();
        let mut q = query();
        q.organization_id = "another-org";
        assert_eq!(
            check(&f, &q, &NONCE, &BINDING, 20, &[]),
            Err(EvidenceError::StructuralPreflight)
        );
        let mut f = fixture();
        f.graph.devices[0].lifecycle = DeviceLifecycle::Revoked;
        assert_eq!(
            check(&f, &query(), &NONCE, &BINDING, 20, &[]),
            Err(EvidenceError::StructuralPreflight)
        );
        let f = fixture();
        assert_eq!(
            check(&f, &query(), &[0; KEY_BYTES], &BINDING, 20, &[]),
            Err(EvidenceError::InvalidContext)
        );
    }

    #[test]
    fn unknown_json_and_key_sizes_are_rejected() {
        let mut f = fixture();
        f.operator.public_key.pop();
        assert_eq!(
            check(&f, &query(), &NONCE, &BINDING, 20, &[]),
            Err(EvidenceError::InvalidCredential)
        );
        assert!(serde_json::from_str::<SignedCredential>(
            r#"{"schema_version":1,"unexpected":"value"}"#,
        )
        .is_err());
        let f = fixture();
        assert_eq!(
            serde_json::from_slice::<SignedCredential>(&serde_json::to_vec(&f.operator).unwrap(),)
                .unwrap(),
            f.operator
        );
    }
}
